/**
 * MOVE-PROFILE-V3-001D: `fmcsaShipments` is NOT a verified FMCSA-reported
 * shipment count. It is generated by lib/fmcsa/refresh/fetch-carrier-core.ts
 * (`Math.max(totalPowerUnits * 50, totalInspections * 10, 1000)`) and by
 * lib/suggestions/publish-snapshot.ts's own estimate — an internal traffic
 * heuristic, not FMCSA evidence. This explains why 569/610 nonzero rows
 * were found to be exactly 1000 (the formula's floor, not a coincidence).
 *
 * `fmcsaComplaints` (== `complaints_last_12m`), by contrast, IS real: it
 * comes from a live call to the FMCSA QC Mobile complaints API
 * (fetchComplaintsByDot in fetch-carrier-core.ts), with a fallback to the
 * carrier-profile API's own totalComplaints/complaintCount field — both
 * genuine FMCSA sources.
 *
 * Per the V3-001D fail-closed decision: the raw complaint COUNT is real
 * evidence and stays. A normalized "per 1,000 shipments" rate is NEVER
 * computed from this denominator, at any volume — the previous interim
 * 20-shipment low-volume threshold governed a rate computation that no
 * longer exists, and has been retired along with it, not just adjusted.
 * No replacement denominator is invented here; if a genuinely verified
 * shipment-volume source is identified later, that is a separate,
 * Founder-reviewed methodology change, not something to reconstruct from
 * this synthetic value.
 */
export type ComplaintEvidence =
  | { status: 'no_record' }
  | { status: 'recorded'; complaints: number };

export const NORMALIZED_COMPLAINT_RATE_UNAVAILABLE_NOTE =
  'Unavailable — a verified shipment denominator is not available. The complaint count above comes from the FMCSA complaints API; shipment volume does not.';

/** Whether this profile has any real FMCSA identity to attach complaint evidence to. */
function hasFmcsaRecord(
  company: Pick<Company, 'usdotNumber' | 'fmcsaLastChecked'>
): boolean {
  return Boolean(company.usdotNumber?.trim()) || Boolean(company.fmcsaLastChecked);
}

/** Real complaint evidence only — never a rate derived from the synthetic shipment estimate. */
export function getComplaintEvidence(
  company: Pick<Company, 'fmcsaComplaints' | 'usdotNumber' | 'fmcsaLastChecked'>
): ComplaintEvidence {
  if (!hasFmcsaRecord(company)) return { status: 'no_record' };
  return { status: 'recorded', complaints: company.fmcsaComplaints ?? 0 };
}

export function formatComplaintEvidenceLabel(evidence: ComplaintEvidence): string {
  if (evidence.status === 'no_record') return 'No FMCSA complaint record on file';
  const word = evidence.complaints === 1 ? 'complaint' : 'complaints';
  return `${evidence.complaints.toLocaleString()} ${word} recorded`;
}

export function formatFmcsaSafetyLabel(rating: Company['fmcsaSafetyRating']): string {
  if (rating === 'Not Rated') {
    return 'Not Rated by FMCSA';
  }
  return rating;
}

export type ProfileReviewSources = {
  editorialRating: number;
  editorialReviewCount: number;
  editorialVolumeLabel: string;
  attributableOnSiteCount: number;
  attributableOnSiteLabel: string;
  googleRating: number | null;
  googleReviewCount: number | null;
  googleAvailable: boolean;
  hasContradictionRisk: boolean;
};

export function buildProfileReviewSources(
  company: Pick<Company, 'id' | 'overallRating' | 'reviewCount'>,
  googleData?: GooglePlacesData | null
): ProfileReviewSources {
  // Live Google snippets take precedence over seed-only counts when present.
  const fromGoogle = company.googleData?.status === 'ok'
    ? (company.googleData.review_snippets ?? []).filter((s) => (s.text?.trim() ?? '').length >= 8).length
    : 0;
  const attributableOnSiteCount = Math.max(
    fromGoogle,
    getCompanyAttributableReviewCount(company.id)
  );
  const googleAvailable = Boolean(
    googleData?.status === 'ok' && googleData.rating != null && googleData.rating > 0
  );
  const googleReviewCount = googleData?.review_count ?? null;
  const editorialReviewCount = company.reviewCount;

  const hasContradictionRisk =
    attributableOnSiteCount > 0 && !googleAvailable && googleData?.status !== 'ok';

  return {
    editorialRating: company.overallRating,
    editorialReviewCount,
    editorialVolumeLabel: formatEditorialReviewVolume(editorialReviewCount),
    attributableOnSiteCount,
    attributableOnSiteLabel: formatAttributableReviewCount(attributableOnSiteCount),
    googleRating: googleAvailable && googleData ? googleData.rating : null,
    googleReviewCount: googleAvailable ? googleReviewCount : null,
    googleAvailable,
    hasContradictionRisk,
  };
}