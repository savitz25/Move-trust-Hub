/** 1200×630 — generated by app/opengraph-image.tsx. Move host never emits another Hub card. */
export const OG_IMAGE = {
  url: `${SHARE_HUB.origin}${SHARE_HUB.ogImagePath}`,
  width: SHARE_HUB.ogWidth,
  height: SHARE_HUB.ogHeight,
  alt: SHARE_HUB.ogAlt,
} as const;

/** Legacy constants kept so leftover imports compile. Do not attach these to Move pages. */
export const LENDER_OG_IMAGE = OG_IMAGE;
export const INSURANCE_OG_IMAGE = OG_IMAGE;

export type OgHub = 'move' | 'lender' | 'insurance';

export function getOgImageForHub(_hub: OgHub = 'move') {
  return OG_IMAGE;
}

export function getSiteNameForHub(_hub: OgHub = 'move') {
  return SITE_NAME;
}

export function buildOpenGraph(
  overrides: {
    title?: string;
    description?: string;
    url?: string;
    type?: 'website' | 'article';
    hub?: OgHub;
    images?: Array<{ url: string; width: number; height: number; alt: string }>;
  } = {}
): NonNullable<Metadata['openGraph']> {
  const hub = overrides.hub ?? 'move';
  const ogImage = overrides.images?.[0] ?? getOgImageForHub(hub);
  // Prefer explicit overrides. Do not fall back to homepage title — that leaked onto
  // company profiles and other deep pages when they only set `metadata.title`.
  return {
    ...(overrides.title ? { title: overrides.title } : {}),
    ...(overrides.description ? { description: overrides.description } : {}),
    url: overrides.url ?? resolveShareOrigin(),
    siteName: getSiteNameForHub(hub),
    type: overrides.type ?? 'website',
    locale: 'en_US',
    images: [ogImage],
  };
}

export function buildTwitter(
  overrides: {
    title?: string;
    description?: string;
    hub?: OgHub;
    images?: Array<{ url: string; width: number; height: number; alt: string }>;
  } = {}
): NonNullable<Metadata['twitter']> {
  const hub = overrides.hub ?? 'move';
  const ogImage = overrides.images?.[0] ?? getOgImageForHub(hub);
  return {
    card: SHARE_HUB.twitterCard,
    ...(overrides.title ? { title: overrides.title } : {}),
    ...(overrides.description ? { description: overrides.description } : {}),
    images: [{ url: ogImage.url, alt: ogImage.alt || SHARE_HUB.ogAlt }],
  };
}

